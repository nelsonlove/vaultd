/**
 * How a bundle is called minified, and why it is two questions rather than one.
 *
 * Mean line length alone calls a generated-but-unminified bundle minified (a
 * single-line concatenation with readable names), and short-identifier ratio
 * alone calls a small hand-written file minified (`fr`, `en`, `id` in a locale
 * table are most of its identifiers). Requiring both, with either one on its
 * own allowed to decide when it is extreme, is what separates the corpus:
 * every esbuild `--minify` output is one enormous line **and** mostly
 * one-and-two-character names, and no unminified bundle is either.
 *
 * Recorded here rather than tuned per call so that the report can say which
 * heuristic answered — see Task 20's report for the measured values.
 */
const MINIFIED_MEAN_LINE = 200;
const MINIFIED_SHORT_RATIO = 0.25;
const MINIFIED_MEAN_LINE_WITH_RATIO = 80;
const MINIFIED_SHORT_RATIO_WITH_LINE = 0.15;

export function scanBundle(pluginId: string, source: string): ScanResult {
  const members = countMembers(source, scannedMembers());
  const apiSymbols: Record<string, number> = {};
  const genericSymbols: Record<string, number> = {};
  for (const [member, hits] of Object.entries(members)) {
    if (GENERIC_MEMBERS.has(member)) genericSymbols[member] = hits;
    else apiSymbols[member] = hits;
  }
  const registrations = countMembers(source, REGISTRATION_MEMBERS);
  const commandSlices = commandRegistrations(source);
  const lifecycleGates = {
    onLayoutReady: countMember(source, "onLayoutReady"),
    layoutReadyRead: countMember(source, "layoutReady"),
    metadataResolved: countEventSubscriptions(source, "resolved"),
    metadataResolve: countEventSubscriptions(source, "resolve"),
  };
  const eventNames = subscribedEvents(source);
  const frameworks = detectFrameworks(source);
  const tier = estimateTier({
    source,
    commandSlices,
    registrations,
    frameworks,
    eventNames,
  });
  return {
    pluginId,
    minified: looksMinified(source),
    bytes: Buffer.byteLength(source, "utf8"),
    apiSymbols,
    genericSymbols,
    lifecycleGates,
    registrations,
    commandIds: commandIdsIn(commandSlices),
    eventNames,
    frameworks,
    crossPlugin: literalsAfter(source, [
      /\.getPlugin\(\s*(["'`])([^"'`]+)\1/g,
      /\.plugins\.plugins\[\s*(["'`])([^"'`]+)\1/g,
    ]),
    internalPlugins: literalsAfter(source, [
      /\.(?:getPluginById|getEnabledPluginById)\(\s*(["'`])([^"'`]+)\1/g,
    ]),
    requiresElectron: /require\(\s*(["'`])electron\1\s*\)/.test(source),
    requiresNode: requiredBuiltins(source),
    tierEstimate: tier.tier,
    tierReasons: tier.reasons,
  };
}

/**
 * The member names a scan counts: every dotted row the host declares, deduped.
 *
 * Deduped because a member is what the bundle shows. `registerHoverLinkSource`
 * is declared twice — once on `Plugin`, once on `Workspace` — and two rows
 * counting the same `\.registerHoverLinkSource\b` matches would report the
 * same call twice and say nothing a reader could act on. The undotted rows
 * (`requestUrl`, `normalizePath`, `Notice`) are deliberately **not** here:
 * they are barrel exports, which a bundle binds, and bindings are renamed.
 */
function scannedMembers(): readonly string[] {
  const members = new Set<string>();
  for (const symbol of declaredSymbols()) {
    const cut = symbol.lastIndexOf(".");
    if (cut === -1) continue;
    const member = symbol.slice(cut + 1);
    if (member.length > 0) members.add(member);
  }
  return [...members];
}

/** One pass over the source for a whole set of members. Zeroes are omitted. */
function countMembers(source: string, members: readonly string[]): Record<string, number> {
  const counts: Record<string, number> = {};
  if (members.length === 0) return counts;
  // Longest first so the alternation reads in the order a human would try the
  // names. Correctness does not depend on it — the trailing `\b` already
  // refuses `.on` inside `.onLayoutReady` — but a shadowed alternative is the
  // classic way a list like this rots.
  const ordered = [...members].sort((a, b) => b.length - a.length);
  const pattern = new RegExp(`\\.(${ordered.join("|")})\\b`, "g");
  for (const match of source.matchAll(pattern)) {
    const member = match[1];
    if (member === undefined) continue;
    counts[member] = (counts[member] ?? 0) + 1;
  }
  return counts;
}

function countMember(source: string, member: string): number {
  return [...source.matchAll(new RegExp(`\\.${member}\\b`, "g"))].length;
}

/** `.on("name"` — the subscription, not the name wherever else it appears. */
function countEventSubscriptions(source: string, name: string): number {
  return [...source.matchAll(new RegExp(`\\.on\\(\\s*(["'\`])${name}\\1`, "g"))].length;
}

/** Every event name subscribed to with a literal, sorted and deduped. */
function subscribedEvents(source: string): readonly string[] {
  const names = new Set<string>();
  for (const match of source.matchAll(/\.on\(\s*(["'`])([^"'`\n]+)\1/g)) {
    const name = match[2];
    if (name !== undefined) names.add(name);
  }
  return [...names].sort();
}

/** The string literals the given patterns capture in group 2, sorted. */
function literalsAfter(source: string, patterns: readonly RegExp[]): readonly string[] {
  const found = new Set<string>();
  for (const pattern of patterns) {
    for (const match of source.matchAll(pattern)) {
      const value = match[2];
      if (value !== undefined) found.add(value);
    }
  }
  return [...found].sort();
}

function requiredBuiltins(source: string): readonly string[] {
  const found = new Set<string>();
  // `[a-z0-9_/]`, with the digit: `http2` is a builtin, and a character class
  // without one reported it absent while its name sat in the list below — the
  // failure shape a list and a matcher that disagree always take.
  for (const match of source.matchAll(/require\(\s*(["'`])(?:node:)?([a-z0-9_/]+)\1\s*\)/g)) {
    const name = match[2];
    if (name !== undefined && NODE_BUILTINS.includes(name)) found.add(name);
  }
  return [...found].sort();
}

function detectFrameworks(source: string): readonly FrameworkName[] {
  const found: FrameworkName[] = [];
  for (const [name, constants] of FRAMEWORK_CONSTANTS) {
    if (constants.some((constant) => source.includes(constant))) found.push(name);
  }
  return found;
}

/**
 * The `addCommand(...)` calls that register a command, and not the others.
 *
 * **A plugin's own method may be called `addCommand`.** obsidian-linter has a
 * settings-tab helper `addCommand(e, i, r)` invoked as `this.addCommand(e, i)`
 * — the same receiver and the same name as the real registration — so neither
 * the name nor the receiver separates them. What separates them is the shape
 * of the argument: Obsidian's takes a `Command` object, and a `Command`
 * without an `id` is not one. The `id:` literal is also exactly what
 * {@link commandIdsIn} reads, so a call this keeps is a call that contributes
 * an id and a call it drops contributed nothing.
 *
 * The cost is a real registration built elsewhere — `this.addCommand(cmd)`
 * with the object in a variable — which this does not see. It was already
 * invisible to `commandIds` for the same reason: an id assembled at runtime is
 * not in the bundle to read. Counting it as a command while being unable to
 * name it would make the tier estimate depend on something no reader could
 * check.
 */
function commandRegistrations(source: string): readonly string[] {
  return argumentSlices(source, "addCommand").filter((slice) => idLiteralIn(slice) !== null);
}

/**
 * Every `addCommand(...)` argument list, as source.
 *
 * Sliced by balancing brackets rather than matched by a regex, because the
 * argument is an object literal holding a callback and a callback holds
 * anything at all. The slice is what the command id is read out of and what
 * the tier estimate asks "does this callback do vault work, and does it build
 * DOM" of — which is the question the study says survives minification.
 */
function argumentSlices(source: string, member: string): readonly string[] {
  const slices: string[] = [];
  const pattern = new RegExp(`\\.${member}\\s*\\(`, "g");
  for (const match of source.matchAll(pattern)) {
    const open = match.index + match[0].length - 1;
    const slice = balancedSlice(source, open);
    if (slice !== null) slices.push(slice);
  }
  return slices;
}

/**
 * From an opening bracket to its partner, strings and comments respected.
 *
 * Answers `null` for an unbalanced tail rather than the rest of the file: a
 * truncated bundle is a bundle this host cannot say anything about, and
 * "everything after the last `addCommand`" would be read as one enormous
 * callback and drag the tier estimate with it.
 */
function balancedSlice(source: string, open: number): string | null {
  const pairs: Record<string, string> = { "(": ")", "[": "]", "{": "}" };
  const stack: string[] = [];
  let index = open;
  while (index < source.length) {
    const char = source[index] ?? "";
    if (char === '"' || char === "'" || char === "`") {
      index = endOfString(source, index);
      continue;
    }
    if (char === "/" && source[index + 1] === "/") {
      const end = source.indexOf("\n", index);
      index = end === -1 ? source.length : end + 1;
      continue;
    }
    if (char === "/" && source[index + 1] === "*") {
      const end = source.indexOf("*/", index + 2);
      index = end === -1 ? source.length : end + 2;
      continue;
    }
    if (char in pairs) {
      stack.push(pairs[char] ?? "");
    } else if (char === ")" || char === "]" || char === "}") {
      if (stack.pop() !== char) return null;
      if (stack.length === 0) return source.slice(open, index + 1);
    }
    index += 1;
  }
  return null;
}

/** The index just past the string starting at `open`. Escapes respected. */
function endOfString(source: string, open: number): number {
  const quote = source[open];
  let index = open + 1;
  while (index < source.length) {
    const char = source[index];
    if (char === "\\") {
      index += 2;
      continue;
    }
    if (char === quote) return index + 1;
    index += 1;
  }
  return source.length;
}

/**
 * The `id:` literal of each command, in registration order.
 *
 * An object key is a property position, so it survives minification exactly as
 * a method name does — `{id:"count-tags",name:"…"}` is what esbuild emits. The
 * leading `(?:^|[{,\s])` is what keeps it from matching a longer key ending in
 * `id`, which is how `choiceId:` or `viewId:` would otherwise be read as the
 * command's own.
 */
function commandIdsIn(slices: readonly string[]): readonly string[] {
  const ids: string[] = [];
  for (const slice of slices) {
    const id = idLiteralIn(slice);
    if (id !== null && !ids.includes(id)) ids.push(id);
  }
  return ids;
}

/** The first `id: "…"` in an argument list, or `null`. See {@link commandIdsIn}. */
function idLiteralIn(slice: string): string | null {
  const match = /(?:^|[{,\s])id\s*:\s*(["'`])([^"'`]*)\1/.exec(slice);
  const id = match?.[2];
  return id !== undefined && id.length > 0 ? id : null;
}

function looksMinified(source: string): boolean {
  const lines = source.split("\n");
  const meanLineLength = source.length / Math.max(lines.length, 1);
  const identifiers = source.match(/[A-Za-z_$][A-Za-z0-9_$]*/g) ?? [];
  const shortRatio =
    identifiers.length === 0
      ? 0
      : identifiers.filter((name) => name.length <= 2).length / identifiers.length;
  if (meanLineLength >= MINIFIED_MEAN_LINE) return true;
  if (shortRatio >= MINIFIED_SHORT_RATIO) return true;
  return (
    meanLineLength >= MINIFIED_MEAN_LINE_WITH_RATIO && shortRatio >= MINIFIED_SHORT_RATIO_WITH_LINE
  );
}

/**
 * Where the logic sits relative to the UI, and why this answer.
 *
 * The order of the rules is the claim. View construction is asked first
 * because a plugin that registers a view and fills it with DOM is the UI
 * whatever else it does; the framework rows come next because a framework is
 * evidence about *how* a plugin renders, not about whether it renders; and the
 * entry-point rules come last, because they are the ones that decide whether a
 * headless host can reach the plugin at all.
 */
function estimateTier(input: {
  source: string;
  commandSlices: readonly string[];
  registrations: Readonly<Record<string, number>>;
  frameworks: readonly FrameworkName[];
  eventNames: readonly string[];
}): { tier: Tier; reasons: readonly string[] } {
  const { source, commandSlices, registrations, frameworks, eventNames } = input;
  const reasons: string[] = [];
  if (hasIndirectPluginBase(source)) reasons.push("indirect Plugin base class");

  const createEl = [...source.matchAll(/\bcreateEl\s*\(/g)].length;
  const views = registrations["registerView"] ?? 0;
  const settingTabs = registrations["addSettingTab"] ?? 0;
  const menuHooks =
    countEventSubscriptions(source, "file-menu") + countEventSubscriptions(source, "editor-menu");
  const delegated =
    (registrations["registerDomEvent"] ?? 0) +
    (registrations["addEventListener"] ?? 0) +
    eventNames.filter((name) => DOM_EVENTS.has(name)).length;
  const workingCommands = commandSlices.filter(
    (slice) => WORK_MEMBERS.some((member) => new RegExp(`\\.${member}\\b`).test(slice)),
  ).length;
  const renderingCommands = commandSlices.filter((slice) => /\bcreateEl\s*\(/.test(slice)).length;

  if (views > 0 && (extendsAView(source) || createEl >= 3) && workingCommands === 0) {
    reasons.push("the body is view construction: a view is registered and its content built as DOM");
    return { tier: 4, reasons };
  }
  if (frameworks.includes("react")) {
    reasons.push("React's own runtime constant is present: the plugin renders itself");
    return { tier: 4, reasons };
  }
  if (frameworks.length > 0) {
    reasons.push(`${frameworks.join(", ")} runtime constants are present: logic is UI-entangled`);
    return { tier: 3, reasons };
  }
  if (settingTabs > 0 && commandSlices.length === 0 && menuHooks === 0) {
    reasons.push("configuration is authored through a settings tab and nothing else is registered");
    return { tier: 3, reasons };
  }
  if (commandSlices.length === 0) {
    if (menuHooks > 0) {
      reasons.push("entry points are harvestable menu hooks");
      return { tier: 2, reasons };
    }
    if (delegated > 0) {
      reasons.push("entry points are DOM-delegated and unreachable headless");
      return { tier: 2, reasons };
    }
    reasons.push("nothing is registered as an entry point: the logic sits in event handlers");
    return { tier: 1, reasons };
  }
  if (workingCommands > 0 && renderingCommands === 0) {
    reasons.push("command callbacks hold vault or metadata calls and build no DOM");
    return { tier: 1, reasons };
  }
  if (renderingCommands > 0) {
    reasons.push("command callbacks build DOM: the logic is entangled with what it draws");
    return { tier: 3, reasons };
  }
  reasons.push("commands are registered but no callback reads as vault or metadata work");
  return { tier: 2, reasons };
}

/**
 * A plugin class two or more hops from `Plugin`.
 *
 * `class extends *.Plugin` is **not** the tier test: the study found 2 of 34
 * sampled bundles where the plugin class extends a local base class that
 * extends `obsidian.Plugin`, and a matcher that only looked one hop reported
 * those two as not being plugins at all. Class names are renamed by
 * minification, but the *structure* — `class A extends B` — is not, so the
 * chain is followable in any build.
 */
function hasIndirectPluginBase(source: string): boolean {
  const bases = new Map<string, string>();
  for (const match of source.matchAll(
    /\bclass\s+([A-Za-z0-9_$]+)\s+extends\s+([A-Za-z0-9_$.]+)/g,
  )) {
    const [, name, base] = match;
    if (name !== undefined && base !== undefined) bases.set(name, base);
  }
  const direct = (base: string): boolean => base === "Plugin" || base.endsWith(".Plugin");
  for (const base of bases.values()) {
    if (direct(base)) continue;
    // Follow the chain, with a visited set: a bundle is allowed to contain a
    // cycle a compiler would reject, and a report generator must not hang on
    // one.
    const seen = new Set<string>();
    let current: string | undefined = base;
    while (current !== undefined && !seen.has(current)) {
      seen.add(current);
      const next: string | undefined = bases.get(current);
      if (next === undefined) break;
      if (direct(next)) return true;
      current = next;
    }
  }
  return false;
}

function extendsAView(source: string): boolean {
  return /\bclass\s+[A-Za-z0-9_$]*\s*extends\s+[A-Za-z0-9_$.]*\b(?:ItemView|FileView|MarkdownView|TextFileView|View)\b/.test(
    source,
  );
}
