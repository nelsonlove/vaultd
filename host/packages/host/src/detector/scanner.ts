/**
 * The static half of the compatibility detector: what a shipped bundle says
 * about itself, read without running it.
 *
 * **Property positions and string literals, never bindings.** The 2026-08-28
 * minification study (`docs/research/headless-plugin-compatibility.md`)
 * measured the boundary: anything reachable as `obj.name` survives
 * minification at 97–100% — Obsidian API methods, DOM APIs, the plugin's own
 * methods, event-name string literals, command ids and names — while any
 * *binding* is renamed and survives only by coincidence (8–25%). Locals and
 * parameters are the obvious half; the load-bearing half is **imported
 * symbols**: `mount`, `requestUrl` and `normalizePath` are bindings in every
 * bundle that imports them, so a scanner counting bare identifiers reports
 * `normalizePath: 0` for a plugin that calls it nine times. So every count
 * here is anchored on a `.` or on a quote, and nothing is anchored on a name
 * standing alone.
 *
 * The same study is why {@link FRAMEWORK_CONSTANTS} holds only constants a
 * framework owns. Two traps it found are fixtures here: the substring `vue`
 * matches a French locale string, and `hydrat` matches ReactDOM. Both are
 * excluded by requiring the full owned constant rather than a word that
 * suggests one.
 *
 * **No AST.** The study also found that minification preserves the AST, so
 * *which callback contains which API calls* is readable from the bundle — and
 * that is what the tier estimate is built from ({@link estimateTier}), rather
 * than from `class extends *.Plugin`, which breaks on indirect base classes (2
 * of the 34 minified bundles sampled). Every estimate carries
 * {@link ScanResult.tierReasons} so a wrong answer is arguable rather than
 * mysterious.
 */

// **Side-effect imports, and they are load-bearing.** `declaredSymbols()` is
// the host's own claim about the surface it serves, and `shim/policy.ts` says
// how it is filled in: "importing a module is all it takes for its surface to
// appear here, with nothing constructed. That is what lets a compatibility
// report be generated by a path that never opens a vault."
//
// So the list below is **every module under `src/` that calls
// `declarePolicy`**, imported for that call and nothing else. Importing only
// `shim/api.ts` is not enough: it reaches most of the shim but not the DOM
// helpers, the prototype extensions, the two plugin registries, the electron
// stub or the module interception, and a scan against that partial surface
// reports a plugin's `document.addEventListener` as touching nothing —
// measured, twice, while this file was being written. A module that starts
// declaring rows has to be added here and the ground truths under
// `host/fixtures/detector/` re-checked, which is the cost of counting against
// the real surface rather than against a copy of it.
