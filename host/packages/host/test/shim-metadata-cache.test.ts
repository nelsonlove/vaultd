import { beforeAll, describe, expect, it } from "vitest";

import { declaredSymbols, policyOf } from "../src/shim/policy";
import { parseFixtureRow, warmFixtureCache } from "../src/testing/fixture-vault";
import { ShimHarness } from "../src/testing/shim-harness";
import type { FixtureNote } from "../src/testing/mirror-harness";
import type { CachedMetadata } from "../src/mirror/metadata";
import type { TFile } from "../src/shim/files";

/**
 * The `MetadataCache` facade over a hydrated mirror.
 *
 * Three of the brief's cases were written against fixtures that could not
 * exercise what the case claimed, and are corrected here rather than passed
 * vacuously — each correction is noted at the case. The fourth, the `changed`
 * event, is driven through the sequencer seam because subscribing this surface
 * to `Mirror.onBatch` is Task 15's job and doing it here would give one batch
 * two event streams.
 *
 * The vault literals are named constants so the warm-up below can parse exactly
 * the document sets the cases use. A fixture row's cache key names the document
 * set **and the parser binary**, so a `vault-core` change makes every one of
 * them cold at once; parsing them here puts that cost in one place with one
 * budget instead of scattering five-second timeouts across the file.
 */
const TAGGED_VAULT = {
  "A.md": "---\ntags: [alpha, beta]\naliases: [Ay]\n---\n#gamma\n",
  "B.md": "#alpha\n",
};
const COUNTED_TAGS_VAULT = {
  "T.md": "#alpha and #alpha again and #beta\n",
  "U.md": "#alpha\n",
};
const ONE_NOTE_VAULT = { "A.md": "# Title\n" };
const ONE_HEADING_VAULT = { "A.md": "# One\n" };
const AMBIGUOUS_VAULT = {
  "Folder/Target.md": "body\n",
  "Other/Target.md": "body\n",
  "Folder/Source.md": "[[Target]]\n",
};
const NAMED_VAULT = {
  "Folder/Target.md": "body\n",
  "Other/Target.md": "body\n",
  "Unique.md": "body\n",
};
const LINKED_VAULT = {
  "A.md": "[[B]] and [[Ghost]]\n",
  "B.md": "body\n",
};
const TWICE_LINKED_VAULT = {
  "A.md": "[[B]] and again [[B]]\n",
  "B.md": "body\n",
};
/**
 * Three Markdown forms that defeat any reconstruction of `original` from a
 * reference's parts, plus a two-level subpath for `displayText`.
 *
 * A link title, an angle-bracket target and an empty alias all reconstruct
 * short — `[lab](Target.md)`, `[b](Odd Name.md)`, `[[Target]]` — while the
 * daemon's span covers the whole text in all three.
 */
const AWKWARD_LINKS_VAULT = {
  "Odd.md":
    '[lab](Target.md "the title")\n\n[b](<Odd Name.md>)\n\n[[Target|]]\n\n[[Target#H1#H2]]\n',
  "Target.md": "body\n",
  "Odd Name.md": "body\n",
};

const VAULTS = [
  TAGGED_VAULT,
  COUNTED_TAGS_VAULT,
  ONE_NOTE_VAULT,
  ONE_HEADING_VAULT,
  AMBIGUOUS_VAULT,
  NAMED_VAULT,
  LINKED_VAULT,
  TWICE_LINKED_VAULT,
  AWKWARD_LINKS_VAULT,
];

beforeAll(() => {
  for (const files of VAULTS) {
    // The same set `FixtureVault` builds: markdown only, path-sorted, one
    // request — anything else is a different cache key and warms nothing.
    warmFixtureCache(
      Object.keys(files)
        .filter((path) => path.toLowerCase().endsWith(".md"))
        .sort()
        .map((path) => ({ path, source: files[path as keyof typeof files] })),
    );
  }
  parseFixtureRow("A.md", "# Two\n");
}, 900_000);

/**
 * First, and deliberately before any harness exists.
 *
 * The policy table is the host's claim about its own surface, so it has to be
 * complete at import — a compatibility report generated by a path that never
 * opens a vault must not silently omit twelve rows. Declaring in the
 * constructor would make this case pass only because some earlier case
 * assembled a shim, which is why it is first in the file.
 */
describe("the MetadataCache policy rows", () => {
  it("are declared at import, with nothing constructed", () => {
    const declared = declaredSymbols();
    expect(declared).toContain("MetadataCache.getFileCache");
    expect(declared).toContain("MetadataCache.getBacklinksForFile");
    expect(policyOf("MetadataCache.getCachedFiles")).toBe("implemented");
    // Declared with a policy, not forgotten: the compatibility report has to be
    // able to say the footnote gap exists. `absent_field` and not `absent`,
    // because none of the three is callable — a plugin reading one gets
    // `undefined`, and a row spelled `absent` would claim a throw that never
    // happens. `test/policy.test.ts` pins one of each kind against the
    // behaviour; these three are the whole `absent_field` set in the host.
    expect(policyOf("CachedMetadata.footnotes")).toBe("absent_field");
    expect(policyOf("CachedMetadata.footnoteRefs")).toBe("absent_field");
    expect(policyOf("CachedMetadata.referenceLinks")).toBe("absent_field");
  });

  /**
   * The behaviour the `absent_field` word claims, against a real cache.
   *
   * The row is a claim about what a plugin sees, so it is worth reading one:
   * the three fields come back `undefined` from a cache this host really built,
   * and nothing throws on the way. That is the difference from `absent`, whose
   * rows throw a typed HeadlessUnsupported when touched — pinned beside this
   * one in `test/policy.test.ts`.
   */
  it("read undefined off a real cache, and throw nothing", async () => {
    const harness = await ShimHarness.withVault(TAGGED_VAULT);
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const cache = harness.app.metadataCache.getFileCache(file);
    expect(cache).not.toBeNull();
    const fields = cache as unknown as Record<string, unknown>;
    expect(fields.footnotes).toBeUndefined();
    expect(fields.footnoteRefs).toBeUndefined();
    expect(fields.referenceLinks).toBeUndefined();
    // And the cache is a real one, not an empty object that would make the
    // three reads pass for the wrong reason.
    expect(cache?.frontmatter).toMatchObject({ tags: ["alpha", "beta"] });
  });
});

describe("MetadataCache", () => {
  it("answers the three undocumented methods tag-wrangler needs", async () => {
    const harness = await ShimHarness.withVault(TAGGED_VAULT);
    const cache = harness.app.metadataCache;
    expect(cache.getCachedFiles().sort()).toEqual(["A.md", "B.md"]);
    expect(cache.getCache("A.md")?.frontmatter).toMatchObject({ tags: ["alpha", "beta"] });
    expect(cache.getCache("missing.md")).toBeNull();
    // Frontmatter tags count too: a note tagged only through `tags:` is not an
    // untagged note, and Obsidian's own tag pane counts it.
    expect(cache.getTags()).toEqual({ "#alpha": 2, "#beta": 1, "#gamma": 1 });
  });

  it("counts a tag once per occurrence, across notes and within one", async () => {
    // Distinguishing: `#alpha` appears twice in `T.md` and once in `U.md`. A
    // getTags that counted notes rather than occurrences would answer 2, and
    // one that counted only the first per note would answer 2 as well — only
    // per-occurrence counting answers 3.
    const harness = await ShimHarness.withVault(COUNTED_TAGS_VAULT);
    expect(harness.app.metadataCache.getTags()).toEqual({ "#alpha": 3, "#beta": 1 });
  });

  it("returns null before a note's position index is warm and the cache after", async () => {
    const harness = await ShimHarness.withVault(ONE_NOTE_VAULT, { warm: false });
    const file = harness.vault.getFileByPath("A.md");
    expect(file).not.toBeNull();
    expect(harness.app.metadataCache.getFileCache(file as TFile)).toBeNull();
    await harness.mirror.warmPositions();
    expect(harness.app.metadataCache.getFileCache(file as TFile)?.headings?.[0]?.heading).toBe(
      "Title",
    );
  });

  it("memoizes per revision and hands back the same object", async () => {
    const harness = await ShimHarness.withVault(ONE_NOTE_VAULT);
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const first = harness.app.metadataCache.getFileCache(file);
    expect(first).not.toBeNull();
    expect(harness.app.metadataCache.getFileCache(file)).toBe(first);
    expect(harness.app.metadataCache.getCache("A.md")).toBe(first);
    expect(harness.app.metadataCache.retainedCount()).toBe(1);
  });

  it("resolves a linkpath through vaultd resolution, not a filename guess", async () => {
    // The brief's fixture wrote `Target` as bare prose, which is no link at all
    // — the case would have passed on the name-search fallback and proved
    // nothing about resolution. A real wikilink makes the daemon answer:
    // `[[Target]]` from `Folder/Source.md` is genuinely ambiguous between the
    // two `Target.md` files, the daemon reports both candidates in its own
    // order, and `firstLinkpathDest` takes that answer rather than re-deciding.
    const harness = await ShimHarness.withVault(AMBIGUOUS_VAULT);
    const dest = harness.app.metadataCache.getFirstLinkpathDest("Target", "Folder/Source.md");
    expect(dest?.path).toBe("Folder/Target.md");
    expect(harness.app.metadataCache.getFirstLinkpathDest("Nope", "Folder/Source.md")).toBeNull();
  });

  it("shortens a link text only when the bare name still reaches the file", async () => {
    const harness = await ShimHarness.withVault(NAMED_VAULT);
    const cache = harness.app.metadataCache;
    const unique = harness.vault.getFileByPath("Unique.md") as TFile;
    expect(cache.fileToLinktext(unique, "Folder/Target.md")).toBe("Unique");
    // Two files share the name, and from `Other/` the bare name reaches the
    // other one — so the full path is the only honest link text.
    const target = harness.vault.getFileByPath("Folder/Target.md") as TFile;
    expect(cache.fileToLinktext(target, "Other/Source.md")).toBe("Folder/Target");
    expect(cache.fileToLinktext(unique, "Folder/Target.md", false)).toBe("Unique.md");
  });

  it("gives a reference the exact source text, titles and brackets included", async () => {
    const harness = await ShimHarness.withVault(AWKWARD_LINKS_VAULT);
    const file = harness.vault.getFileByPath("Odd.md") as TFile;
    const links = harness.app.metadataCache.getFileCache(file)?.links ?? [];
    expect(links.map((link) => link.original)).toEqual([
      // Reconstructing from `kind` + `raw_target` + `display` produces
      // `[lab](Target.md)`, `[b](Odd Name.md)` and `[[Target]]` — short in all
      // three, and `original` is what a plugin searches the body for.
      '[lab](Target.md "the title")',
      "[b](<Odd Name.md>)",
      "[[Target|]]",
      "[[Target#H1#H2]]",
    ]);
    for (const link of links) {
      expect(link.original.length).toBe(link.position.end.offset - link.position.start.offset);
    }
  });

  it("spells every subpath separator in displayText, not just the first", async () => {
    const harness = await ShimHarness.withVault(AWKWARD_LINKS_VAULT);
    const file = harness.vault.getFileByPath("Odd.md") as TFile;
    const links = harness.app.metadataCache.getFileCache(file)?.links ?? [];
    const nested = links.find((link) => link.original === "[[Target#H1#H2]]");
    // A string-pattern `replace` would have left `Target > H1#H2`.
    expect(nested?.displayText).toBe("Target > H1 > H2");
    expect(nested?.link).toBe("Target#H1#H2");
  });

  it("exposes resolvedLinks, unresolvedLinks, and backlinks from the mirror", async () => {
    // The brief's `"A.md": "B and Ghost\n"` contains no links, so nothing could
    // have landed in either table. Written as links, it does.
    const harness = await ShimHarness.withVault(LINKED_VAULT);
    const cache = harness.app.metadataCache;
    expect(cache.resolvedLinks["A.md"]).toEqual({ "B.md": 1 });
    expect(cache.unresolvedLinks["A.md"]).toEqual({ Ghost: 1 });
    const backlinks = cache.getBacklinksForFile(harness.vault.getFileByPath("B.md") as TFile);
    expect(backlinks.keys()).toEqual(["A.md"]);
    expect(backlinks.get("A.md")).toHaveLength(1);
    expect(backlinks.count()).toBe(1);
    expect(backlinks.get("A.md")?.[0]).toMatchObject({ link: "B", original: "[[B]]" });
    // The position is the referring note's, converted through its own index.
    expect(backlinks.get("A.md")?.[0]?.position.start.offset).toBe(0);
    expect(backlinks.get("missing.md")).toBeNull();
  });

  it("counts backlink keys, not backlink entries", async () => {
    // Distinguishing: one source note linking the same target twice. `count()`
    // is 1 under the "keys" reading and 2 under "items"; the previous case,
    // with one link from one note, could not tell them apart.
    const harness = await ShimHarness.withVault(TWICE_LINKED_VAULT);
    const backlinks = harness.app.metadataCache.getBacklinksForFile(
      harness.vault.getFileByPath("B.md") as TFile,
    );
    expect(backlinks.keys()).toEqual(["A.md"]);
    expect(backlinks.get("A.md")).toHaveLength(2);
    expect(backlinks.count()).toBe(1);
    expect(harness.app.metadataCache.resolvedLinks["A.md"]).toEqual({ "B.md": 2 });
  });

  it("fires changed with file, data, and cache in Obsidian's argument order", async () => {
    const harness = await ShimHarness.withVault(ONE_HEADING_VAULT);
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const seen: Array<[string, string, string | undefined]> = [];
    harness.app.metadataCache.on("changed", (...args) => {
      const [changed, data, cache] = args as unknown as [TFile, string, CachedMetadata | null];
      seen.push([changed.path, data, cache?.headings?.[0]?.heading]);
    });

    // A real write, answered with a really-parsed row, so the mirror holds the
    // new heading and a position index rebuilt from the new bytes. The harness's
    // own `writeNote` helper answers the refetch with an empty row, which would
    // have made the cache assertion below pass on `undefined`.
    const row = parseFixtureRow("A.md", "# Two\n");
    const writing = harness.vault.adapter.write("A.md", "# Two\n");
    const request = await harness.expectRequest("write_note");
    harness.respondOk(request.id, "write_note", { generation: 2, revision: row.revision });
    harness.setFileContent("A.md", "# Two\n");
    await harness.answerRefetch(2, [asFixtureNote(row)]);
    await writing;

    // The seam Task 15's lifecycle sequencer calls. It is not wired to
    // `Mirror.onBatch` here on purpose: one batch must produce one ordered run
    // of events, and that ordering is the sequencer's to own.
    harness.app.metadataCache.notifyChanged(file, "# Two\n");
    expect(seen).toEqual([["A.md", "# Two\n", "Two"]]);
  });

  it("carries the last assembled cache into deleted and then forgets it", async () => {
    const harness = await ShimHarness.withVault(ONE_HEADING_VAULT);
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const before = harness.app.metadataCache.getFileCache(file);
    expect(before?.headings?.[0]?.heading).toBe("One");
    const seen: Array<CachedMetadata | null> = [];
    harness.app.metadataCache.on("deleted", (...args) => {
      seen.push((args as unknown as [TFile, CachedMetadata | null])[1]);
    });
    harness.app.metadataCache.notifyDeleted(file);
    // The same object the reader got, not a rebuild: the mirror's row is gone
    // by the time Task 15 calls this, so this is the only copy left.
    expect(seen[0]).toBe(before);
    expect(harness.app.metadataCache.retainedCount()).toBe(0);
    // Fired twice, the second carries nothing: the entry is gone.
    harness.app.metadataCache.notifyDeleted(file);
    expect(seen[1]).toBeNull();
  });

  it("keeps the payload when a reader asks about a note whose row is already gone", async () => {
    // The interaction between two separately-right fixes. `notifyDeleted` hands
    // over the last assembled cache; a reader meeting a gone row must therefore
    // not evict it. A `vault.on("delete")` handler asking "what was in that
    // file?" is the obvious way to be that reader, and if the read wiped the
    // entry the event would then fire with `null`.
    const harness = await ShimHarness.withVault(ONE_HEADING_VAULT);
    const cache = harness.app.metadataCache;
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const before = cache.getFileCache(file);
    expect(before?.headings?.[0]?.heading).toBe("One");

    // Take the row out of the mirror, as a delete does.
    const removing = harness.mirror.applyMutation(2, ["A.md"]);
    await harness.answerRefetch(2, [], { absent: ["A.md"] });
    await removing;
    expect(harness.mirror.note("A.md")).toBeUndefined();

    // The reader. Answers null — there is no row — and must leave the retained
    // assembly alone.
    expect(cache.getFileCache(file)).toBeNull();
    expect(cache.retainedCount()).toBe(1);

    const seen: Array<CachedMetadata | null> = [];
    cache.on("deleted", (...args) => {
      seen.push((args as unknown as [TFile, CachedMetadata | null])[1]);
    });
    cache.notifyDeleted(file);
    expect(seen[0]).toBe(before);
    expect(cache.retainedCount()).toBe(0);
  });

  it("carries null for a note nothing ever read", async () => {
    // The hole named on `notifyDeleted`: this surface is not told a note is
    // about to go, so it can only hand over what somebody already asked for.
    const harness = await ShimHarness.withVault(ONE_HEADING_VAULT);
    const file = harness.vault.getFileByPath("A.md") as TFile;
    const seen: Array<CachedMetadata | null> = [];
    harness.app.metadataCache.on("deleted", (...args) => {
      seen.push((args as unknown as [TFile, CachedMetadata | null])[1]);
    });
    harness.app.metadataCache.notifyDeleted(file);
    expect(seen).toEqual([null]);
  });
});

/** A parsed row as the refetch answer wants it. */
function asFixtureNote(row: ReturnType<typeof parseFixtureRow>): FixtureNote {
  return {
    path: row.path,
    revision: row.revision,
    properties: [...row.properties],
    aliases: [...row.aliases],
    headings: [...row.headings],
    blocks: [...row.blocks],
    tags: [...row.tags],
    sections: [...row.sections],
    listItems: [...row.listItems],
    outgoing: [...row.outgoing],
  };
}
